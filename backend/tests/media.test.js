'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const sqlite = require('sqlite3');

test('video upload, range playback and live profile/friendship permissions', async t => {
  const db = new sqlite.Database(':memory:');
  const exec = sql => new Promise((resolve, reject) => db.exec(sql, e => e ? reject(e) : resolve()));
  const run = (sql, args = []) => new Promise((resolve, reject) => db.run(sql, args, e => e ? reject(e) : resolve()));
  await exec(`CREATE TABLE users(id INTEGER PRIMARY KEY,name TEXT,surname TEXT,role TEXT);
    INSERT INTO users VALUES(1,'Анна',NULL,'user'),(2,'Борис',NULL,'user'),(3,'Вера',NULL,'user');
    CREATE TABLE posts(id TEXT PRIMARY KEY,place TEXT);
    CREATE TABLE local_place_owners(place_id TEXT,owner_id TEXT);`);
  const stats = require('../statistics')(db);
  const connections = require('../connections')(db, stats.auth);
  const profiles = require('../account-profile')(db, stats.auth);
  const media = require('../media')(db, stats.auth);
  const social = require('../social')(db, stats.auth, media);
  media.setCanRead(social.canReadMedia);
  await connections.initialize(); await profiles.initialize(); await media.initialize(); await social.initialize(); await social.initialize();
  const app = express();
  app.use('/api', profiles.router); app.use('/api/media', media.router);
  app.use(express.json()); app.use('/api/social', social.router); app.use('/api', stats.router);
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await new Promise(resolve => db.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const tokens = [null, ...[1, 2, 3].map(id => stats.issue({ id: String(id), role: 'user' }))];
  const call = (path, user, method = 'GET', body, mime = 'application/json') => fetch(base + path, { method, headers: { 'Content-Type': mime, ...(user ? { Authorization: `Bearer ${tokens[user]}` } : {}) }, ...(body === undefined ? {} : { body: mime === 'application/json' ? JSON.stringify(body) : body }) });
  // Signature-only binary fixture tests the API byte contract, not device recording/codecs.
  const bytes = Buffer.concat([Buffer.from([0, 0, 0, 24]), Buffer.from('ftypisom'), Buffer.alloc(100, 7)]);
  assert.equal((await call('/api/media', null, 'POST', bytes, 'video/mp4')).status, 401);
  assert.equal((await call('/api/media', 1, 'POST', Buffer.from('bad'), 'video/mp4')).status, 415);
  assert.equal((await call('/api/media', 1, 'POST', Buffer.alloc(media.limit + 1), 'video/mp4')).status, 413);
  const uploaded = await call('/api/media', 1, 'POST', bytes, 'video/mp4');
  assert.equal(uploaded.status, 201); const file = await uploaded.json();
  assert.equal(file.kind, 'video');
  assert.equal((await fetch(base + `/api/media/${file.id}`)).status, 401);
  assert.deepEqual(Buffer.from(await (await fetch(base + file.url)).arrayBuffer()), bytes);
  const partial = await fetch(base + file.url, { headers: { Range: 'bytes=4-11' } });
  assert.equal(partial.status, 206); assert.equal(partial.headers.get('content-range'), `bytes 4-11/${bytes.length}`);
  assert.equal(Buffer.from(await partial.arrayBuffer()).toString(), 'ftypisom');
  assert.equal((await fetch(base + file.url, { headers: { Range: 'bytes=9999-' } })).status, 416);
  const jpeg = Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x02, 0xff, 0xd9]);
  const photoUpload = await call('/api/media', 1, 'POST', jpeg, 'image/jpeg');
  assert.equal(photoUpload.status, 201);
  const photo = await photoUpload.json();
  assert.equal(photo.kind, 'image');
  const photoStory = await call('/api/social/items', 1, 'POST', { kind: 'story', body: 'Фото', mediaId: photo.id, requestId: 'photo-story-0001' });
  assert.equal(photoStory.status, 201);
  const photoItem = await photoStory.json();
  assert.equal(photoItem.mediaKind, 'image');
  assert.deepEqual(Buffer.from(await (await fetch(base + photoItem.mediaUrl)).arrayBuffer()), jpeg);
  assert.equal((await call(`/api/social/items/${photoItem.id}`, 2)).status, 404);
  const post = { kind: 'post', body: '', mediaId: file.id, requestId: 'video-post-0001' };
  assert.equal((await call('/api/social/items', 2, 'POST', post)).status, 403);
  const created = await call('/api/social/items', 1, 'POST', post);
  assert.equal(created.status, 201); const item = await created.json();
  assert.equal(item.mediaKind, 'video'); assert.ok(item.mediaUrl);
  assert.equal((await (await call('/api/social/items', 1, 'POST', post)).json()).id, item.id);
  assert.equal((await call(`/api/social/items/${item.id}`, 2)).status, 404);
  await run('INSERT INTO friendships(low_id,high_id,requested_by,accepted) VALUES(1,2,1,1)');
  const friendItem = await (await call(`/api/social/items/${item.id}`, 2)).json();
  assert.equal((await fetch(base + friendItem.mediaUrl)).status, 200);
  const friendPhoto = await (await call(`/api/social/items/${photoItem.id}`, 2)).json();
  assert.equal((await fetch(base + friendPhoto.mediaUrl)).status, 200);
  await run('DELETE FROM friendships');
  assert.equal((await fetch(base + friendItem.mediaUrl)).status, 404);
  assert.equal((await fetch(base + friendPhoto.mediaUrl)).status, 404);
  assert.equal((await call('/api/account/profile', 1, 'PATCH', { isPrivate: false })).status, 200);
  const publicItem = await (await call(`/api/social/items/${item.id}`, 3)).json();
  assert.equal((await fetch(base + publicItem.mediaUrl)).status, 200);
  await call('/api/account/profile', 1, 'PATCH', { isPrivate: true });
  assert.equal((await fetch(base + publicItem.mediaUrl)).status, 404);
  assert.equal((await call(`/api/social/items/${item.id}/like`, 3, 'PUT')).status, 404);
  await call('/api/account/profile', 1, 'PATCH', { isPrivate: false });
  const story = await (await call('/api/social/items', 1, 'POST', { ...post, kind: 'story', requestId: 'video-story-0001' })).json();
  const storyForFriend = await (await call(`/api/social/items/${story.id}`, 2)).json();
  // The post still grants read access to this same file; expire it too to test revocation.
  await run('DELETE FROM social_items WHERE id=?', [item.id]);
  await run('UPDATE social_items SET expires_at=? WHERE id=?', ['2000-01-01T00:00:00Z', story.id]);
  assert.equal((await fetch(base + storyForFriend.mediaUrl)).status, 404);
  await call('/api/logout', 1, 'POST');
  assert.equal((await fetch(base + file.url)).status, 401);
});
