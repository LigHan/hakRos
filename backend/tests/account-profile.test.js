'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const sqlite = require('sqlite3');
const { mkdtemp, rm } = require('node:fs/promises');
const { tmpdir } = require('node:os');
const path = require('node:path');
const createAccountProfile = require('../account-profile');
const createStatistics = require('../statistics');

test('профиль: био, аватарка, приватность, доступ и сохранение после перезапуска', async t => {
  const dir = await mkdtemp(path.join(tmpdir(),'hakros-profile-'));
  const dbPath = path.join(dir,'profile.db');
  let db = new sqlite.Database(dbPath);
  const exec = sql => new Promise((resolve,reject) => db.exec(sql,error => error ? reject(error) : resolve()));
  await exec(`CREATE TABLE users(id INTEGER PRIMARY KEY,name TEXT,surname TEXT,role TEXT,email TEXT);
    INSERT INTO users VALUES (2,'Анна',NULL,'user','secret@example.test'),(10,'Борис',NULL,'user','private@example.test'),(20,'Кафе',NULL,'company','company@example.test');
    CREATE TABLE friendships(low_id INTEGER,high_id INTEGER,accepted INTEGER);`);
  const stats = createStatistics(db);
  let profiles = createAccountProfile(db,stats.auth);
  await profiles.initialize(); await profiles.initialize();
  const app = express(); app.use('/api',profiles.router);
  const server = await new Promise(resolve => { const s=app.listen(0,'127.0.0.1',()=>resolve(s)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await new Promise(resolve => db.close(resolve)); await rm(dir,{recursive:true,force:true}); });
  const token = id => stats.issue({id:String(id),role:id===20?'company':'user'});
  const request = async (route,id,body) => {
    const res=await fetch(base+route,{method:body?'PATCH':'GET',headers:{'Content-Type':'application/json',...(id?{Authorization:`Bearer ${token(id)}`}:{})},...(body?{body:JSON.stringify(body)}:{})});
    return {status:res.status,data:await res.json()};
  };
  assert.equal((await request('/api/account/profile')).status,401);
  assert.equal((await request('/api/profiles/2')).status,401);
  assert.equal((await request('/api/account/profile',2)).data.isPrivate,true);
  assert.equal((await request('/api/account/profile',2,{bio:'Люблю прогулки',isPrivate:false})).status,200);
  let publicProfile=(await request('/api/profiles/2',10)).data;
  assert.equal(publicProfile.canView,true); assert.equal(publicProfile.bio,'Люблю прогулки'); assert.equal('email' in publicProfile,false);
  assert.equal((await request('/api/account/profile',2,{bio:'x'.repeat(501)})).status,400);
  assert.equal((await request('/api/account/profile',2,{isPrivate:'true'})).status,400);
  assert.equal((await request('/api/account/profile',20,{isPrivate:true})).status,400);
  await request('/api/account/profile',2,{isPrivate:true});
  const locked=(await request('/api/profiles/2',10)).data;
  assert.equal(locked.canView,false); assert.equal(locked.bio,'');
  await exec('INSERT INTO friendships VALUES (2,10,0)');
  assert.equal(await profiles.canViewProfile('10','2'),false);
  await exec('UPDATE friendships SET accepted=1');
  assert.equal(await profiles.canViewProfile('10','2'),true);
  assert.equal((await request('/api/profiles/2',10)).data.bio,'Люблю прогулки');
  await exec('DELETE FROM friendships');
  assert.equal(await profiles.canViewProfile('10','2'),false);
  assert.equal((await request('/api/account/profile',2,{avatarBase64:Buffer.from('<svg/>').toString('base64')})).status,400);
  const jpeg=Buffer.from([0xff,0xd8,0xff,0xe0,0xff,0xd9]).toString('base64');
  const saved=(await request('/api/account/profile',2,{avatarBase64:jpeg})).data;
  assert.match(saved.avatar,/^\/api\/profile-avatars\/2\//);
  const avatar=await fetch(base+saved.avatar);
  assert.equal(avatar.status,200); assert.equal(avatar.headers.get('content-type'),'image/jpeg');
  assert.equal((await request('/api/account/profile',2,{bio:'После перезапуска'})).data.avatar,saved.avatar);
  await new Promise(resolve => db.close(resolve)); db=new sqlite.Database(dbPath);
  profiles=createAccountProfile(db,stats.auth); await profiles.initialize();
  const restored=await profiles.getProfile('2');
  assert.equal(restored.bio,'После перезапуска'); assert.equal(restored.avatar,saved.avatar); assert.equal(restored.isPrivate,true);
});
