'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const sqlite = require('sqlite3');
const createStatistics = require('../statistics');

test('социальная лента: права, публикация, истории и реакции', async t => {
  const db = new sqlite.Database(':memory:');
  const exec = sql => new Promise((resolve, reject) => db.exec(sql, e => e ? reject(e) : resolve()));
  const run = (sql, args=[]) => new Promise((resolve, reject) => db.run(sql, args, e => e ? reject(e) : resolve()));
  await exec(`CREATE TABLE users (id INTEGER PRIMARY KEY, name TEXT, surname TEXT, role TEXT);
    INSERT INTO users VALUES (1,'Анна',NULL,'user'),(2,'Борис',NULL,'user'),(3,'Вера',NULL,'user'),(4,'Компания',NULL,'company');
    CREATE TABLE posts (id TEXT PRIMARY KEY, place TEXT, userHandle TEXT, userAvatar TEXT, bio TEXT);
    INSERT INTO posts VALUES ('cafe','Кафе','','','');
    CREATE TABLE local_place_owners (place_id TEXT, owner_id TEXT); INSERT INTO local_place_owners VALUES ('cafe','4');`);
  const stats = createStatistics(db), connections = require('../connections')(db, stats.auth), social = require('../social')(db, stats.auth);
  await connections.initialize(); await social.initialize(); await social.initialize();
  const app = express(); app.use(express.json()); app.use('/social', social.router); app.use('/connections', connections.router);
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await new Promise(resolve => db.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const tokens = [null, ...[1,2,3,4].map(id => stats.issue({ id: String(id), role: id === 4 ? 'company' : 'user' }))];
  async function request(path, user, method = 'GET', body) {
    const response = await fetch(base + path, { method, headers: { 'Content-Type':'application/json', ...(user ? { Authorization:`Bearer ${tokens[user]}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, data: await response.json() };
  }
  const post = { kind:'post', body:'Моё место', requestId:'create-post-0001' };
  assert.equal((await request('/social/feed', null)).status, 401);
  assert.equal((await request('/social/items',1,'POST',{...post,placeId:'cafe'})).status,403);
  const created = await request('/social/items',1,'POST',post);
  assert.equal(created.status,201); const id = created.data.id;
  assert.equal((await request('/social/items',1,'POST',post)).data.id,id);
  assert.equal((await request('/social/items',1,'POST',{...post,body:'другое'})).status,409);
  assert.deepEqual((await request('/social/feed',2)).data,[]);
  assert.equal((await request(`/social/items/${id}/like`,2,'PUT')).status,404);
  await request('/connections/friends/2/request',1,'PUT');
  assert.deepEqual((await request('/social/feed',2)).data,[]);
  await request('/connections/friends/1/accept',2,'PUT');
  assert.equal((await request('/social/feed',2)).data[0].body,post.body);
  assert.equal((await request(`/social/items/${id}/like`,2,'PUT')).data.likes,1);
  assert.equal((await request(`/social/items/${id}/like`,2,'PUT')).data.likes,1);
  assert.equal((await request(`/social/items/${id}/like`,2,'DELETE')).data.likes,0);
  const comment = {body:'Здорово',requestId:'comment-000001'};
  assert.equal((await request(`/social/items/${id}/comments`,2,'POST',comment)).status,200);
  await request(`/social/items/${id}/comments`,2,'POST',comment);
  assert.equal((await request(`/social/items/${id}/comments`,2)).data.length,1);
  assert.equal((await request(`/social/items/${id}/comments`,3)).status,404);
  const story = await request('/social/items',1,'POST',{kind:'story',body:'История',requestId:'create-story-001'});
  assert.equal(story.status,201);
  assert.equal(Date.parse(story.data.expiresAt)-Date.parse(story.data.createdAt),86400000);
  await run('UPDATE social_items SET expires_at=? WHERE id=?',['2000-01-01T00:00:00.000Z',story.data.id]);
  assert.equal((await request(`/social/items/${story.data.id}`,2)).status,404);
  assert.equal((await request('/social/items',4,'POST',{kind:'post',body:'Кафе',placeId:'bad',requestId:'company-post-01'})).status,403);
  const company = await request('/social/items',4,'POST',{kind:'post',body:'Кафе',placeId:'cafe',requestId:'company-post-01'});
  assert.equal(company.status,201);
  assert.equal((await request(`/social/items/${company.data.id}`,2)).status,404);
  await request('/connections/places/cafe',2,'PUT');
  assert.equal((await request(`/social/items/${company.data.id}`,2)).status,200);
  const repost = await request('/social/items',2,'POST',{kind:'post',body:'Советую',originalId:id,requestId:'repost-0000001'});
  assert.equal(repost.status,201);
  await request('/connections/friends/3/request',2,'PUT'); await request('/connections/friends/2/accept',3,'PUT');
  assert.equal((await request(`/social/items/${repost.data.id}`,3)).status,404);
  await request('/connections/friends/2',1,'DELETE');
  assert.equal((await request(`/social/items/${id}`,2)).status,404);
  assert.equal((await request(`/social/items/${id}/comments`,2)).status,404);
  assert.equal((await request(`/social/items/${repost.data.id}`,2)).status,404);
});
